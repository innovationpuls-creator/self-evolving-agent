import { chromium } from 'playwright-core';
import { mkdir, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const base = new URL('./evidence/revision-review/', import.meta.url);
await mkdir(base, { recursive: true });
const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [];
page.on('pageerror', e => errors.push(String(e)));
await page.goto('http://127.0.0.1:4177/');
await page.evaluate(() => document.fonts.ready);
await page.screenshot({ path: new URL('session-1440.png',base).pathname });
const positions = await page.evaluate(() => {
  const a = document.querySelector('.messages').getBoundingClientRect();
  const b = document.querySelector('.composer').getBoundingClientRect();
  return { scrollBottom:a.bottom, composerTop:b.top };
});
assert(positions.scrollBottom <= positions.composerTop + 1, 'composer overlaps reading area');
const draft = page.getByRole('textbox', { name: '发送给 Agent' });
await draft.fill('切换模块后应保留的草稿');
await page.getByRole('button', { name:'Memory', exact:true }).click();
await page.screenshot({ path: new URL('memory-current-1440.png',base).pathname });
await page.getByRole('button', { name: '修订认识', exact:false }).click();
await page.getByLabel('修改理由').fill('核对显示流程');
await page.getByLabel('演示：保存时已有更新').check();
assert(await page.getByRole('button', { name:'保存修订' }).isDisabled(), 'conflict did not block save');
assert(await page.getByText('版本冲突', { exact:true }).isVisible());
await page.screenshot({path:new URL('memory-conflict.png',base).pathname});
await page.getByRole('button', {name:'取消',exact:true}).click();
await page.getByRole('button', { name:'Session',exact:true }).click();
assert.equal(await draft.inputValue(),'切换模块后应保留的草稿','draft lost on navigation');
await page.getByRole('button', {name:'Evolution',exact:true}).click();
await page.screenshot({path:new URL('evolution-proposal-1440.png',base).pathname});
await page.getByRole('button',{name:'创建目标讨论 →'}).click();
await page.getByLabel('讨论内容').fill('完善报告对缺失附件的标注');
await page.getByRole('button',{name:'发送讨论'}).click();
await page.getByRole('button',{name:'审阅开发授权 ↗'}).click();
await page.screenshot({path:new URL('authorization-1440.png',base).pathname});
const border = await page.evaluate(() => {
  const modal=document.querySelector('.r4-dialog');
  const select=document.querySelector('.page-heading select');
  const input=modal?.querySelector('input:not([type=checkbox])');
  return [select,input].map(el => getComputedStyle(el).borderRadius);
});
assert(border.every(x=>x==='6px'), 'form controls have inconsistent corner radius: '+border);
await page.keyboard.press('Escape');
await page.setViewportSize({width:390,height:900});
await page.getByRole('button',{name:'Session',exact:true}).click();
await page.screenshot({path:new URL('session-390.png',base).pathname});
const toolbar = await page.evaluate(() => {
 const a=[...document.querySelectorAll('.compose-actions button')].find(b=>b.textContent.includes('引用'));
 const b=[...document.querySelectorAll('.compose-actions button')].find(b=>b.textContent.includes('发送'));
 return {top1:a.getBoundingClientRect().top,top2:b.getBoundingClientRect().top,overflow:document.documentElement.scrollWidth-innerWidth};
});
assert(Math.abs(toolbar.top1-toolbar.top2)<8,'composer send action wrapped');
assert(toolbar.overflow<=0,'mobile horizontal overflow');
assert.deepEqual(errors,[]);
await writeFile(new URL('checks.json',base),JSON.stringify({positions,toolbar,border,errors,checks:['session composer does not cover reading','navigation retains draft','memory conflict blocks save','consistent control border radius','mobile toolbar stays in one row','no horizontal overflow']},null,2));
await browser.close();
